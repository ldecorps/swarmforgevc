#!/usr/bin/env node
'use strict';

// Regenerate src/bridge/zappaWorkTitlesData.ts from lib.ru song list + supplements.
// Usage: node extension/scripts/generate-zappa-work-titles.mjs [path-to-listofsongs.html]

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const repoRoot = path.resolve(__dirname, '..', '..');
const defaultSource = path.join(repoRoot, 'extension', 'data', 'zappa-source.html');
const outPath = path.join(repoRoot, 'extension', 'src', 'bridge', 'zappaWorkTitlesData.ts');

const sourcePath = process.argv[2] ?? defaultSource;
if (!fs.existsSync(sourcePath)) {
  try {
    fs.mkdirSync(path.dirname(defaultSource), { recursive: true });
    execFileSync('curl', ['-fsSL', 'http://lib.ru/lat/SONGS/frankzappa/listofsongs.txt', '-o', defaultSource], {
      stdio: 'inherit',
    });
  } catch {
    process.stderr.write(`missing source ${sourcePath}\n`);
    process.exit(1);
  }
}

const html = fs.readFileSync(sourcePath, 'utf8');
const works = new Set();

function cleanTitle(s) {
  return s.replace(/\s+/g, ' ').replace(/\s*\(& comments\)\s*/gi, '').trim();
}

function isValidTitle(t) {
  if (!t || t.length < 3 || t.length > 90) return false;
  if (!/[a-zA-Z]/.test(t)) return false;
  if (/^[-_,.'"#\\]|^---$|^, The$/.test(t)) return false;
  if (/VALIGN|WIDTH=|\.epub|\.html|font size/i.test(t)) return false;
  if (/^Part (One|Two|II|III)\b/i.test(t)) return false;
  if (/^(Intro|segue|reprise|Original Version)$/i.test(t)) return false;
  if (/^YCDTOSA\s*\d+$/i.test(t)) return false;
  if (/^only comments/i.test(t)) return false;
  return true;
}

const rowRe = /<td[^>]*WIDTH="54%"[^>]*><font><font size=-1>([\s\S]*?)<\/font><\/font><\/td>/gi;
let m;
while ((m = rowRe.exec(html))) {
  const left = cleanTitle(m[1].replace(/<[^>]+>/g, ''));
  if (isValidTitle(left)) {
    works.add(left.replace(/, The$/, ''));
  }
}

const albumRe = /"([^"]{3,90})"/g;
while ((m = albumRe.exec(html))) {
  const album = cleanTitle(m[1]);
  if (isValidTitle(album)) {
    works.add(album);
  }
}

const extra = [
  'Freak Out!', 'Absolutely Free', 'Lumpy Gravy', "We're Only In It For The Money",
  'Uncle Meat', 'Hot Rats', 'Burnt Weeny Sandwich', 'Weasels Ripped My Flesh',
  "Chunga's Revenge", 'Fillmore East - June 1971', '200 Motels', 'Waka/Jawaka',
  'The Grand Wazoo', 'Over-Nite Sensation', "Apostrophe(')", 'Roxy & Elsewhere',
  'One Size Fits All', 'Bongo Fury', 'Zoot Allures', 'Zappa In New York',
  'Studio Tan', 'Sleep Dirt', 'Orchestral Favorites', 'Sheik Yerbouti',
  "Joe's Garage", 'Tinseltown Rebellion', 'You Are What You Is',
  'Ship Arriving Too Late To Save A Drowning Witch', 'The Man From Utopia',
  'The Perfect Stranger', 'Them Or Us', 'Thing-Fish', 'Francesco Zappa',
  'Frank Zappa Meets The Mothers Of Prevention', 'Jazz From Hell',
  'Broadway The Hard Way', 'Guitar', 'Civilization Phaze III', 'The Yellow Shark',
  'Dance Me This', 'Halloween', 'Roxy: The Movie', 'Cruising With Ruben & The Jets',
  'Mothermania', 'Playground Psychotics', 'Ahead Of Their Time', 'Make A Jazz Noise Here',
  "Shut Up 'n Play Yer Guitar", 'Trance-Fusion', "Chicago '78", 'Peaches En Regalia',
  'Cosmik Debris', 'Inca Roads', 'Florentine Pogen', "Echidna's Arf (Of You)",
  "San Ber'dino", "Don't Eat The Yellow Snow", 'Muffin Man', 'Watermelon In Easter Hay',
  'The Torture Never Stops', 'City Of Tiny Lites', 'Keep It Greasey', 'Billy The Mountain',
  'Montana', 'Black Napkins', 'The Illinois Enema Bandit',
  "You Can't Do That On Stage Anymore", 'Funky Nothingness', 'Wazoo',
];
extra.forEach((t) => {
  if (isValidTitle(t)) {
    works.add(t);
  }
});

const sorted = [...works].sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
const contents = `// GENERATED by extension/scripts/generate-zappa-work-titles.mjs — do not edit by hand.
export const ZAPPA_WORK_TITLE_SOURCE =
  'http://lib.ru/lat/SONGS/frankzappa/listofsongs.txt (parsed ${new Date().toISOString().slice(0, 10)}) + official supplements';

export const ZAPPA_WORK_TITLES: readonly string[] = ${JSON.stringify(sorted, null, 2)} as const;
`;
fs.writeFileSync(outPath, contents);
process.stdout.write(`wrote ${sorted.length} titles to ${outPath}\n`);
